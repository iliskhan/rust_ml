import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { practiceTopics, practiceRelease } from '../src/practice/all-catalog.ts'

// Authoring only. The browser never imports this generator or SQL bundle.
const hash = (value) => createHash('sha256').update(value).digest('hex')
const id = (value) => { const h = hash(`${practiceRelease}:${value}`); return `${h.slice(0,8)}-${h.slice(8,12)}-4${h.slice(13,16)}-8${h.slice(17,20)}-${h.slice(20,32)}` }
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`
const release = id('release')
const languages = ['python', 'javascript', 'rust']
const totals = { topics: practiceTopics.length, requirements: 0, exercises: 0, variants: 0 }
const topicIds = new Set(), exerciseIds = new Set()
// A/B alternatives share only their explicitly authored transfer group.
// Other exercises remain separate requirements so passing one cannot erase a gap.
function requirementsFor(topic) {
  const pairs = new Map()
  for (const exercise of topic.exercises) {
    const pair = exercise.mode === 'transfer' && exercise.id.match(/^(.*)\.transfer-([ab])$/)
    if (pair) pairs.set(pair[1], new Set([...(pairs.get(pair[1]) ?? []), pair[2]]))
  }
  return topic.exercises.map(exercise => {
    const pair = exercise.mode === 'transfer' && exercise.id.match(/^(.*)\.transfer-([ab])$/)
    const independent = Boolean(pair && pairs.get(pair[1]).size === 2)
    return { exercise, key: independent ? pair[1] + ':transfer' : exercise.id,
      rule: independent ? 'independent' : 'pass', required: exercise.mode === 'guided' || independent }
  })
}
const lines = ['-- Generated by supabase/generate-seed.mjs from the reviewed public authoring catalog.', '-- Content-only release: no hidden grading fixtures or executable runtime is claimed.', 'begin;']
lines.push(`insert into public.practice_releases(id,release_key,version,title) values ('${release}',${quote(practiceRelease)},1,'Практика RustML · авторский учебный каталог');`)
for (const [position, topic] of practiceTopics.entries()) {
  if (topicIds.has(topic.id)) throw new Error('Duplicate topic ID: ' + topic.id)
  topicIds.add(topic.id)
  const topicId = id(topic.id)
  const exerciseRequirements = requirementsFor(topic)
  const groups = [...new Map(exerciseRequirements.map(({ key, rule, required }) => [key, { key, rule, required }])).values()]
  if (!groups.some(g => g.required)) throw new Error('Topic has no required exercise: ' + topic.id)
  totals.requirements += groups.length
  lines.push(`insert into public.practice_topics(id,release_id,topic_key,title,lesson_anchor,position) values ('${topicId}','${release}',${quote(topic.id)},${quote(topic.title)},${quote('#'+topic.lessonId)},${position});`)
  for (const [n, group] of groups.entries()) lines.push(`insert into public.practice_requirements(id,topic_id,release_id,requirement_key,position,required,completion_rule) values ('${id(group.key)}','${topicId}','${release}',${quote(group.key)},${n},${group.required},'${group.rule}');`)
  for (const [n, { exercise, key }] of exerciseRequirements.entries()) {
    if (exerciseIds.has(exercise.id)) throw new Error('Duplicate exercise ID: ' + exercise.id)
    exerciseIds.add(exercise.id)
    totals.exercises++
    const exerciseId = id(exercise.id)
    lines.push(`insert into public.practice_exercises(id,topic_id,release_id,requirement_id,exercise_key,position,objective,prompt_markdown) values ('${exerciseId}','${topicId}','${release}','${id(key)}',${quote(exercise.id)},${n},${quote(exercise.title)},${quote(exercise.prompt+'\n\n'+exercise.formula)});`)
    for (const language of languages) {
      totals.variants++
      const variantId = id(exercise.id+':'+language)
      const starter = exercise.starter[language]
      const entrypoint = starter.match(/(?:function|def|fn)\s+(\w+)/)?.[1]
      if (!entrypoint) throw new Error('Missing entrypoint: '+exercise.id+':'+language)
      const runnerSpec = { enabled: false, reason: 'isolated_runner_not_verified', artifact_kind: 'authored_help_only', language, entrypoint }
      const bundle = { grading_tests: [], runner_spec: runnerSpec, hints: exercise.hints, reference_solution: exercise.solution[language], explanation: exercise.explanation }
      lines.push(`insert into public.practice_variants(id,exercise_id,release_id,language,starter_code,entrypoint,public_tests,runtime_digest) values ('${variantId}','${exerciseId}','${release}','${language}',${quote(starter)},${quote(entrypoint)},${json(exercise.fixtures.map(f=>({input:JSON.parse(f.input),output:JSON.parse(f.output)})))},null);`)
      lines.push(`insert into private.practice_bundles(variant_id,release_id,bundle_sha256,grading_tests,expected_tests,runner_spec,hints,reference_solution,explanation) values ('${variantId}','${release}','${hash(JSON.stringify(bundle))}','[]',0,${json(runnerSpec)},array[${exercise.hints.map(quote).join(',')}]::text[],${quote(exercise.solution[language])},${quote(exercise.explanation)});`)
    }
  }
}
lines.push(`select private.publish_practice_release('${release}');`, 'commit;', '')
writeFileSync(new URL('migrations/202610120003_anchor_content.sql', import.meta.url), lines.join('\n'))
console.log(JSON.stringify({ release: practiceRelease, ...totals, grading: "disabled" }))
